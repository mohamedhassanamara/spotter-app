// Ranks before / after "only my routines count by default", and the first suggestions for the Pull
// routine's Machine Single-Arm Reverse Fly, from the owner's real Liftoff export. Writes
// docs/RANK_POLICY.md. Skipped unless LIFTOFF_CSV points at the file (never committed):
//
//   LIFTOFF_CSV=~/Desktop/DOCS/liftoff_workout_data.csv LIFTOFF_BW=108@2026-04-19,106@2026-10-11 \
//     flutter test test/tool/rank_policy_report_test.dart
import 'dart:io';

import 'package:drift/drift.dart' show driftRuntimeOptions;
import 'package:drift/native.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:spotter/bootstrap.dart';
import 'package:spotter/core/db/database.dart';
import 'package:spotter/core/domain/equipment.dart';
import 'package:spotter/core/domain/gym.dart';
import 'package:spotter/core/domain/muscles.dart';
import 'package:spotter/core/settings/app_settings.dart';
import 'package:spotter/features/coach/data/coach_context.dart';
import 'package:spotter/features/coach/domain/energy.dart';
import 'package:spotter/features/coach/domain/suggestion_engine.dart';
import 'package:spotter/features/import/data/liftoff_import_service.dart';
import 'package:spotter/features/library/data/exercise_repository.dart';
import 'package:spotter/features/program/data/program_repository.dart';
import 'package:spotter/features/ranks/data/rank_exclusions.dart';
import 'package:spotter/features/program/domain/program.dart';
import 'package:spotter/features/ranks/data/ranks_repository.dart';
import 'package:spotter/features/ranks/domain/ranks.dart';
import 'package:spotter/features/readiness/data/readiness_repository.dart';
import 'package:spotter/features/recovery/domain/recovery.dart';
import 'package:spotter/features/workout/data/history_repository.dart';
import 'package:spotter/features/workout/data/routine_repository.dart';

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();
  driftRuntimeOptions.dontWarnAboutMultipleDatabases = true;
  final path = Platform.environment['LIFTOFF_CSV']?.replaceFirst('~', Platform.environment['HOME'] ?? '~');

  test('rank policy before/after + single-arm reverse fly suggestions → docs/RANK_POLICY.md', () async {
    final now = DateTime(2026, 10, 13, 9);
    final weighIns = [
      for (final part in (Platform.environment['LIFTOFF_BW'] ?? '106').split(','))
        part.contains('@') ? (double.parse(part.split('@')[0]), DateTime.parse(part.split('@')[1])) : (double.parse(part), now),
    ]..sort((a, b) => a.$2.compareTo(b.$2));
    final db = AppDatabase(NativeDatabase.memory());
    addTearDown(db.close);
    await bootstrapDatabase(db);
    for (final (kg, at) in weighIns) {
      await BodyWeightRepository(db).addManual(kg, at: at);
    }
    final catalog = await ExerciseRepository(db).watchCatalog().first;
    final service = LiftoffImportService(db);
    await service.commit(await service.preview(File(path!).readAsStringSync(), catalog: catalog),
        catalog: catalog, settings: const SettingsModel(), now: now);

    final cat = await ExerciseRepository(db).watchCatalog().first;
    final history = await HistoryRepository(db).load(cat);
    final standards = await RanksRepository.loadStandards();
    final timeline = RanksRepository.timeline(await BodyWeightRepository(db).all());
    final routines = await RoutineRepository(db).watchRoutines().first;
    final myIds = {for (final r in routines) for (final e in r.exercises) e.exerciseId};
    RankSummary compute(Set<String> excluded) => RanksRepository.compute(
        history: history, standards: standards, catalog: cat, bodyweights: timeline, now: now, excluded: excluded, myExerciseIds: myIds);

    // Before: everything with a standard counted except what the import itself left out (the old rule).
    final before = compute({'One-Legged_Cable_Kickback'});
    final excluded = await RankExclusions(db).load();
    final after = compute(excluded);

    String sc(RankScore? s) => s == null ? 'unranked' : s.label;
    final out = StringBuffer()
      ..writeln('# Ranks: only my routines count by default')
      ..writeln()
      ..writeln('Generated by `test/tool/rank_policy_report_test.dart` from my Liftoff export (history up to 11 Oct; the CSV is '
          'not in the repo), as of 13 Oct 2026. **Sessions logged in the app since 11 Oct are not in this export.** On the phone, '
          'the one-time migration also switches on every exercise with a completed in-app working set.')
      ..writeln()
      ..writeln('## Exercises that count now (${after.exercises.length})')
      ..writeln()
      ..writeln('| Exercise | Why it counts | Rank (was) | Rank (now) |')
      ..writeln('|---|---|---|---|');
    final beforeBy = {for (final r in before.exercises) r.exerciseId: r};
    final policy = await RankExclusions(db).policy();
    for (final r in [...after.exercises]..sort((a, b) => b.score.value.compareTo(a.score.value))) {
      out.writeln('| ${r.name} | ${policy.sourceOf(r.exerciseId) == RankSource.routine ? 'in a routine' : policy.sourceOf(r.exerciseId).name} | '
          '${sc(beforeBy[r.exerciseId]?.score)} | ${sc(r.score)} |');
    }
    out
      ..writeln()
      ..writeln('## Switched off now (had a rank before: ${before.exercises.length - after.exercises.length} exercises)')
      ..writeln()
      ..writeln('| Exercise | Rank it had |')
      ..writeln('|---|---|');
    final nowIds = {for (final r in after.exercises) r.exerciseId};
    for (final r in before.exercises.where((r) => !nowIds.contains(r.exerciseId))) {
      out.writeln('| ${r.name} | ${sc(r.score)} |');
    }
    out
      ..writeln()
      ..writeln('## Overall, regions, muscles')
      ..writeln()
      ..writeln('| | Before | After |')
      ..writeln('|---|---|---|')
      ..writeln('| **Overall** | ${sc(before.overall)} | ${sc(after.overall)} |');
    for (final r in BodyRegion.values) {
      out.writeln('| Region · ${r.label} | ${sc(before.regions[r]?.score)} | ${sc(after.regions[r]?.score)} |');
    }
    final unranked = <String>[];
    for (final m in Muscle.values) {
      final b = before.muscles[m]?.score, a = after.muscles[m]?.score;
      out.writeln('| Muscle · ${m.label} | ${sc(b)} | ${sc(a)} |');
      if (b != null && a == null) unranked.add(m.label);
    }
    out
      ..writeln()
      ..writeln('Muscles that became unranked: ${unranked.isEmpty ? 'none' : unranked.join(', ')}.');

    // --- Pull: Machine Single-Arm Reverse Fly ---
    const id = ProgramRepository.singleArmReverseFlyId;
    final info = cat[id]!;
    final program = await ProgramRepository.load();
    final pull = routines.firstWhere((r) => r.routine.name == 'Pull');
    final re = pull.exercises.firstWhere((e) => e.exerciseId == id);
    final logs = history.logsFor(id);
    final energy = EnergyContext.compute(now: now, bodyweights: [for (final (kg, at) in weighIns) (at, kg)], nutrition: const []);
    final recovery = computeRecovery(history, now: now);
    final pres = prescribeSets(program: program, slotIds: decodeSlots(re.programSlots), sets: re.targetSets);
    out
      ..writeln()
      ..writeln('## Pull: Machine Single-Arm Reverse Fly')
      ..writeln()
      ..writeln('- Routine row: position ${pull.exercises.indexOf(re) + 1} of ${pull.exercises.length}, where Machine Reverse Fly was; '
          '${re.targetSets} sets from program slots ${decodeSlots(re.programSlots).join(' + ')} (the program\'s 1-Arm Reverse Pec Deck: 1×20 then 1×10, both to failure, 0–1 warm-ups, rest 1–2 min); Jeff\'s demo attached.')
      ..writeln('- **History mapped to:** `$id` ("${info.name}", the entry the Liftoff import made from "One Arm Machine Reverse Fly"; '
          '${logs.length} logged session${logs.length == 1 ? '' : 's'}${logs.isEmpty ? '' : ': ${logs.map((l) => '${l.date.day} Oct ${l.sets.map((s) => '${formatKg(s.weight)} kg × ${s.reps}').join(', ')}').join('; ')}'}). '
          'Not used: "One Arm Cable Reverse Fly" (19 sessions, but a cable, so its stack numbers don\'t carry over) and the two-arm "Machine Reverse Fly" (42 sessions).')
      ..writeln()
      ..writeln('| Set | Reps | Green day | Red day |')
      ..writeln('|---|---|---|---|');
    for (final (i, p) in pres.indexed) {
      Suggestion s(int score) => const SuggestionEngine().suggest(SuggestionInput(
            range: p.repRange,
            targetSets: 1,
            targetRir: p.targetRir ?? 0,
            increment: Increments.defaults.of(info.equipmentKind),
            equipment: info.equipmentKind,
            history: history.logsForRange(id, p.repRange),
            readiness: ExerciseReadiness(score: score, calibrating: false),
            now: now,
            bodyweight: 0,
            assisted: false,
            rangeMatched: logs.isEmpty || history.hasLogsAtRange(id, p.repRange),
            grid: gridForExercise(GymEquipment.defaults, history, info),
            compound: info.isCompound,
            fatigued: [for (final m in fatiguedPrimaries(recovery, [info.targets])) m.label],
            energy: energy,
          ));
      final g = s(60), r = s(30);
      out.writeln('| ${i + 1} | ${p.repRange} | **${formatKg(g.weight)} kg × ${g.reps}** | ${formatKg(r.weight)} kg × ${r.reps} |');
    }
    out
      ..writeln()
      ..writeln('The reps column is the slot\'s range; "× reps" is the suggestion. Stack steps are the 5 kg default.');
    File('docs/RANK_POLICY.md').writeAsStringSync(out.toString());
    // ignore: avoid_print
    print(out);
  }, skip: path == null ? 'set LIFTOFF_CSV to the Liftoff export to regenerate docs/RANK_POLICY.md' : null);
}
