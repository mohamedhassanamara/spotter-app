// Audit of every exercise in my routines and history: name ↔ library entry, GIF ↔ movement and equipment, ranking entry ↔ exercise.
// → docs/EXERCISE_AUDIT.md. Skipped unless LIFTOFF_CSV points at the export:
//
//   LIFTOFF_CSV=~/Desktop/DOCS/liftoff_workout_data.csv LIFTOFF_BW=108@2026-04-19,106@2026-10-11 \
//     flutter test test/tool/exercise_audit_report_test.dart
import 'dart:io';

import 'package:drift/drift.dart' show driftRuntimeOptions;
import 'package:drift/native.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:spotter/bootstrap.dart';
import 'package:spotter/core/db/database.dart';
import 'package:spotter/core/settings/app_settings.dart';
import 'package:spotter/features/debug/data/exercise_audit_repository.dart';
import 'package:spotter/features/import/data/liftoff_import_service.dart';
import 'package:spotter/features/library/data/exercise_repository.dart';
import 'package:spotter/features/tutorials/data/media_repository.dart';

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();
  driftRuntimeOptions.dontWarnAboutMultipleDatabases = true;
  final path = Platform.environment['LIFTOFF_CSV']?.replaceFirst('~', Platform.environment['HOME'] ?? '~');

  test('exercise audit → docs/EXERCISE_AUDIT.md', () async {
    final now = DateTime(2026, 10, 13, 9);
    final db = AppDatabase(NativeDatabase.memory());
    addTearDown(db.close);
    await bootstrapDatabase(db);
    final catalog0 = await ExerciseRepository(db).watchCatalog().first;
    final service = LiftoffImportService(db);
    await service.commit(await service.preview(File(path!).readAsStringSync(), catalog: catalog0), catalog: catalog0, settings: const SettingsModel(), now: now);
    final catalog = await ExerciseRepository(db).watchCatalog().first;
    final media = MediaRepository(db);
    await media.ensureMatched(catalog, now: now);

    final rows = await ExerciseAuditRepository(db).load(catalog);

    String cell(String? s) => (s == null || s.isEmpty ? '–' : s).replaceAll('|', '/');
    final out = StringBuffer()
      ..writeln('# Exercise audit')
      ..writeln()
      ..writeln('Every exercise in my routines and history (${rows.length}): the library entry, the GIF and the ranking entry, checked against the strict rule '
          '(**same movement and same equipment, otherwise no GIF**; a ranking entry must be the same movement on the same equipment). '
          'Generated by `test/tool/exercise_audit_report_test.dart`; the same check runs live in Settings → Debug menu → Exercise audit.')
      ..writeln()
      ..writeln('| Exercise (library) | My name(s) | Name source | Equipment | GIF | GIF check | Ranked as | Rank check | Sets | Routine |')
      ..writeln('|---|---|---|---|---|---|---|---|---|---|');
    for (final r in rows) {
      out.writeln('| ${cell(r.exercise.name)} | ${cell(r.names.join('; '))} | ${r.nameSource} | ${cell(r.exercise.equipment)} | '
          '${cell(r.gifName == null ? null : '${r.gifName} (${r.gifEquipments.join('/')}; ${r.gifSource})')} | ${r.gif.name} | '
          '${cell(r.standardName)} | ${r.standard.name} | ${r.setCount} | ${r.inRoutines ? 'yes' : ''} |');
    }
    final bad = rows.where((r) => r.hasIssue).toList();
    out
      ..writeln()
      ..writeln('## Findings (${bad.length})')
      ..writeln();
    for (final r in bad) {
      out.writeln('- **${r.exercise.name}** (`${r.exercise.id}`): ${r.issues.join('; ')}');
    }
    File('docs/EXERCISE_AUDIT.md').writeAsStringSync(out.toString());
    // ignore: avoid_print
    print('audit rows ${rows.length}, findings ${bad.length}');
  }, skip: path == null ? 'set LIFTOFF_CSV to regenerate docs/EXERCISE_AUDIT.md' : false, timeout: const Timeout(Duration(minutes: 5)));
}
