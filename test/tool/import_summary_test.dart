// Imports the owner's real Liftoff export into an in-memory database and writes
// docs/IMPORT_SUMMARY.md. Skipped unless LIFTOFF_CSV points at the file (never committed):
//
//   LIFTOFF_CSV=~/Desktop/DOCS/liftoff_workout_data.csv LIFTOFF_BW=80 flutter test test/tool/import_summary_test.dart
import 'dart:io';
import 'dart:math' as math;

import 'package:drift/drift.dart' show driftRuntimeOptions;
import 'package:drift/native.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:intl/intl.dart';
import 'package:spotter/bootstrap.dart';
import 'package:spotter/core/db/database.dart';
import 'package:spotter/core/domain/equipment.dart';
import 'package:spotter/core/domain/training.dart';
import 'package:spotter/core/settings/app_settings.dart';
import 'package:spotter/features/coach/data/coach_context.dart';
import 'package:spotter/features/coach/domain/suggestion_engine.dart';
import 'package:spotter/features/import/data/liftoff_import_service.dart';
import 'package:spotter/features/library/data/exercise_repository.dart';
import 'package:spotter/features/library/domain/load_kinds.dart';
import 'package:spotter/features/program/data/program_repository.dart';
import 'package:spotter/features/ranks/data/ranks_repository.dart';
import 'package:spotter/features/readiness/data/readiness_repository.dart';
import 'package:spotter/features/workout/data/history_repository.dart';
import 'package:spotter/features/workout/data/routine_repository.dart';
import 'package:spotter/features/workout/data/session_repository.dart';

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();
  driftRuntimeOptions.dontWarnAboutMultipleDatabases = true;
  final path = Platform.environment['LIFTOFF_CSV']?.replaceFirst('~', Platform.environment['HOME'] ?? '~');

  test('import the real Liftoff export and write docs/IMPORT_SUMMARY.md', () async {
    final now = DateTime(2026, 10, 12, 9);
    final bw = double.tryParse(Platform.environment['LIFTOFF_BW'] ?? '') ?? 80;
    final db = AppDatabase(NativeDatabase.memory());
    addTearDown(db.close);
    await bootstrapDatabase(db);
    await BodyWeightRepository(db).addManual(bw, at: now);
    final catalog = await ExerciseRepository(db).watchCatalog().first;
    final service = LiftoffImportService(db);
    final csv = File(path!).readAsStringSync();

    final preview = await service.preview(csv, catalog: catalog);
    final result = await service.commit(preview, catalog: catalog, settings: const SettingsModel(weeklyGoal: 5), now: now);
    final again = await service.preview(csv, catalog: await ExerciseRepository(db).watchCatalog().first);
    expect(again.newSessions, isEmpty, reason: 'idempotent');

    final cat = await ExerciseRepository(db).watchCatalog().first;
    final history = await HistoryRepository(db).load(cat);
    final standards = await RanksRepository.loadStandards();
    final bwLoaded = RanksRepository.bodyweightLoadedIds(standards, cat);
    final fmt = DateFormat('d MMM y');
    final out = StringBuffer()
      ..writeln('# Liftoff import summary')
      ..writeln()
      ..writeln('Generated by `test/tool/import_summary_test.dart` from the owner\'s Liftoff export '
          '(the CSV itself is not in the repo). Re-run with `LIFTOFF_CSV=… flutter test test/tool/import_summary_test.dart`.')
      ..writeln()
      ..writeln('## Totals')
      ..writeln()
      ..writeln('| | |')
      ..writeln('|---|---|')
      ..writeln('| Sessions imported | ${result.sessions} |')
      ..writeln('| Sets imported | ${result.sets} |')
      ..writeln('| Date range | ${fmt.format(preview.first!)} → ${fmt.format(preview.last!)} |')
      ..writeln('| Training days | ${{for (final s in preview.parse.sessions) DateFormat('y-MM-dd').format(s.start)}.length} |')
      ..writeln('| Rows skipped | ${preview.parse.skipped.length} |')
      ..writeln('| Custom exercises created | ${result.customsCreated} |')
      ..writeln('| Re-import of the same file | ${again.alreadyImported} already imported, 0 new |')
      ..writeln('| Achievements unlocked (no XP) | ${result.achievements.isEmpty ? '—' : result.achievements.map((a) => a.title).join(', ')} |')
      ..writeln('| Bodyweight used for assisted/bodyweight lifts | ${formatKg(bw)} kg |')
      ..writeln()
      ..writeln('## Skipped rows')
      ..writeln()
      ..writeln('| Line | Exercise | Reason |')
      ..writeln('|---|---|---|');
    for (final s in preview.parse.skipped) {
      out.writeln('| ${s.line} | ${s.exercise.isEmpty ? '(none)' : s.exercise} | ${s.reason} |');
    }
    out
      ..writeln()
      ..writeln('## Name mapping')
      ..writeln()
      ..writeln('Order: assets/liftoff_name_map.json (ids, then custom entries) → my routine names → exact library name → fuzzy (≥ 80 %) → custom. '
          'Unmatched names become custom exercises unless picked in the preview.')
      ..writeln()
      ..writeln('| Liftoff name | Sets | → Spotter exercise | Method | Confidence |')
      ..writeln('|---|---|---|---|---|');
    for (final m in preview.mappings) {
      out.writeln('| ${m.liftoffName} | ${m.sets} | ${m.exerciseName} (`${m.exerciseId}`) | ${m.method.label} | ${(m.confidence * 100).round()} % |');
    }
    final byId = <String, List<String>>{};
    for (final m in preview.mappings) {
      (byId[m.exerciseId!] ??= []).add(m.liftoffName);
    }
    final shared = byId.entries.where((e) => e.value.length > 1).toList();
    out
      ..writeln()
      ..writeln('Liftoff names sharing one Spotter exercise (one history): '
          '${shared.isEmpty ? 'none' : shared.map((e) => '${e.value.join(' + ')} → `${e.key}`').join('; ')}. '
          'To split them, give one a `custom` entry in assets/liftoff_name_map.json.');
    final unmatched = preview.unmatched;
    out
      ..writeln()
      ..writeln('Unmatched names: ${unmatched.isEmpty ? 'none' : unmatched.map((m) => m.liftoffName).join(', ')}.')
      ..writeln()
      ..writeln('## Current best per lift')
      ..writeln()
      ..writeln('"Recent" is the best set of the last 3 sessions, which is what suggestions build on. '
          '"All-time" is only for PRs and history. e1RM counts imported sets as RPE 10 '
          '(bodyweight added for bodyweight and assisted lifts).')
      ..writeln()
      ..writeln('| Exercise | Sessions | Last done | Recent best set | Recent e1RM | All-time best set | All-time e1RM |')
      ..writeln('|---|---|---|---|---|---|---|');
    String load(String id, double w) => isAssisted(id) ? '${formatKg(-w)} kg assist' : (w == 0 ? 'BW' : '${formatKg(w)} kg');
    final rows = <(String, String)>[];
    for (final id in history.exerciseIds) {
      final logs = history.logsFor(id).where((l) => l.hasWorkingSets).toList();
      if (logs.isEmpty) continue;
      final b = bwLoaded.contains(id) || isAssisted(id) ? bw : 0.0;
      (LoggedSet, double) best(Iterable<ExerciseSessionLog> ls) {
        LoggedSet? top;
        var e = 0.0;
        for (final l in ls) {
          for (final s in l.workingSets) {
            final v = s.e1rm(bodyweight: b);
            if (top == null || v > e) {
              top = s;
              e = v;
            }
          }
        }
        return (top!, e);
      }

      final recent = best(logs.sublist(math.max(0, logs.length - 3)));
      final all = best(logs);
      final name = history.sessions.reversed.expand((s) => s.exercises).firstWhere((e) => e.exerciseId == id).name;
      rows.add((
        name,
        '| $name | ${logs.length} | ${fmt.format(logs.last.date)} | ${load(id, recent.$1.weight)} × ${recent.$1.reps} | '
            '${recent.$2.toStringAsFixed(1)} | ${load(id, all.$1.weight)} × ${all.$1.reps} | ${all.$2.toStringAsFixed(1)} |',
      ));
    }
    rows.sort((a, b) => a.$1.compareTo(b.$1));
    for (final r in rows) {
      out.writeln(r.$2);
    }

    final ranks = RanksRepository.compute(history: history, standards: standards, bodyweightLoaded: bwLoaded, bodyweight: bw, now: now);
    final ranked = [...ranks.exercises]..sort((a, b) => b.score.value.compareTo(a.score.value));
    out
      ..writeln()
      ..writeln('## Ranks after import')
      ..writeln()
      ..writeln('Overall: ${ranks.overall?.label ?? 'unranked'}. Ranked lifts, best first (current standards; '
          'section 8 replaces them with the 20-muscle model):')
      ..writeln()
      ..writeln('| Lift | Rank | Best e1RM | Ratio to bodyweight |')
      ..writeln('|---|---|---|---|');
    for (final r in ranked) {
      out.writeln('| ${r.standard.name} | ${r.score.label} | ${r.bestE1rm.toStringAsFixed(1)} kg | ${r.ratio.toStringAsFixed(2)} |');
    }

    // First suggestion per routine exercise: start each routine exactly like the app does
    // (neutral readiness), read what it prescribes, then discard the session.
    out
      ..writeln()
      ..writeln('## First suggestion per routine exercise')
      ..writeln()
      ..writeln('Neutral readiness (no Health data in this run). Each routine started as the app does on ${fmt.format(now)}, then discarded.')
      ..writeln();
    final program = await ProgramRepository.load();
    final routines = await RoutineRepository(db).watchRoutines().first;
    final sessions = SessionRepository(db);
    for (final r in routines) {
      final coach = CoachContext(
        history: await HistoryRepository(db).load(cat),
        readiness: null,
        overloaded: const {},
        freezes: const {},
        increments: Increments.defaults,
        now: now,
        bodyweight: bw,
        bodyweightLoaded: bwLoaded,
      );
      final id = await sessions.start(name: r.routine.name, coach: coach, catalog: cat, routine: r, program: program);
      out
        ..writeln('### ${r.routine.name}')
        ..writeln()
        ..writeln('| Exercise | Suggestion | Basis |')
        ..writeln('|---|---|---|');
      final exRows = await (db.select(db.sessionExercises)..where((t) => t.sessionId.equals(id))).get();
      exRows.sort((a, b) => a.position.compareTo(b.position));
      for (final e in exRows) {
        final s = StoredSuggestion.fromRow(e);
        final basis = s?.why.where((w) => !w.startsWith('Readiness')).take(2).join(' ') ?? '';
        out.writeln('| ${e.displayName ?? cat[e.exerciseId]?.name} | ${s?.headline ?? '—'} | ${basis.replaceAll('|', '/')} |');
      }
      out.writeln();
      await sessions.discard(id);
    }

    File('docs/IMPORT_SUMMARY.md').writeAsStringSync(out.toString());
    // ignore: avoid_print
    print('Wrote docs/IMPORT_SUMMARY.md: ${result.sessions} sessions, ${result.sets} sets');
  }, skip: path == null ? 'set LIFTOFF_CSV to the Liftoff export to regenerate docs/IMPORT_SUMMARY.md' : false, timeout: const Timeout(Duration(minutes: 5)));
}
